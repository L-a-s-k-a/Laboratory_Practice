#include "init.h"

// 简单的软件延时函数 / Простая программная функция задержки
void delay(volatile int t)
{
    while(t--) {}
}

//为STMViewer定义的全局系统状态变量 / Глобальные переменные состояния системы для STMViewer ==========
// 这些变量将被STMViewer读取以实时显示系统状态 / Эти переменные будут считываться STMViewer для отображения текущего состояния системы в реальном времени
volatile uint8_t pc8_switch_state;      // PC8引脚当前电平状态 (0=低, 1=高) / Текущий уровень напряжения на пине PC8 (0=низкий, 1=высокий)
volatile uint8_t pc13_switch_state;     // PC13引脚当前电平状态 (0=低, 1=高) / Текущий уровень напряжения на пине PC13 (0=низкий, 1=высокий)
volatile uint8_t operational_mode;      // 当前工作模式 (0=模式0, 1=模式1) / Текущий режим работы (0=режим0, 1=режим1)
volatile uint8_t lighting_sequence;     // LED点亮序列 (0=全灭, 1=LED1亮, 2=LED2亮, 3=LED3亮, 4=全灭) / Последовательность включения светодиодов (0=все выключены, 1=светодиод LED1 включен, 2=LED2 включен, 3=LED3 включен, 4=все выключены)
volatile uint8_t pc13_press_total;      // PC13按钮总按下次数 / Общее количество нажатий кнопки PC13
volatile uint32_t switch_operation_count; // 模式切换总次数 / Общее количество переключений режимов

int main(void)
{
    // 调用统一的初始化函数，包含所有GPIO的配置 / Вызов унифицированной функции инициализации, включающей все настройки GPIO
    GPIO_Init_Self_Def();

    // 初始化全局变量 / Инициализация глобальных переменных
    pc8_switch_state = 1;       // 初始状态为高（未按下） / Начальное состояние - высокий уровень (кнопка не нажата)
    pc13_switch_state = 0;      // 初始状态为低（未按下） / Начальное состояние - низкий уровень (кнопка не нажата)
    operational_mode = 0;       // 初始进入模式0 / Начальный вход в режим 0
    lighting_sequence = 0;      // 初始所有LED熄灭 / Все светодиоды изначально выключены
    pc13_press_total = 0;       // 总按压次数清零 / Обнуление общего количества нажатий
    switch_operation_count = 0; // 模式切换次数清零 / Обнуление количества переключений режимов

    int mode = 0;                   // 当前模式 (0 或 1) / Текущий режим (0 или 1)
    int button1_last = 1;           // PC8 上一次状态 / Предыдущее состояние PC8
    int button2_last = 1;           // PC13 上一次状态 / Предыдущее состояние PC13
    int button2_count = 0;          // PC13 连按次数 / Счетчик нажатий PC13
    int led_step = 0;               // LED 依次点亮计数 / Счетчик последовательного включения светодиодов

    // 初始状态：PC8作为输入（检测按钮） / Начальное состояние: PC8 как вход (обнаружение кнопки)
    set_PC8_as_input();

    while(1)
    {
        int btn1, btn2;
        // 在模式0时，需要读取PC8按钮状态 / В режиме 0 необходимо считать состояние кнопки PC8
        if(mode == 0)
        {
            set_PC8_as_input();
            delay(10);  // 短暂延时确保模式切换稳定 / Краткая задержка для стабилизации переключения режима
            btn1 = (GPIOC->IDR >> BUTTON1_PIN) & 1;
            // 更新全局变量 / Обновление глобальной переменной
            pc8_switch_state = btn1;
        }
        else
        {
            // 模式1时，PC8作为输出控制LED4 / В режиме 1 PC8 как выход управляет светодиодом LED4
            set_PC8_as_output();
            GPIOC->BSRR = (1 << BUTTON1_PIN);  // 输出高电平，点亮LED4 / Высокий уровень на выходе, включение светодиода LED4
            btn1 = 1;  // 模式1时按钮状态设为1（未按下） / В режиме 1 состояние кнопки установлено на 1 (не нажата)
            // 更新全局变量 / Обновление глобальной переменной
            pc8_switch_state = 1;
        }
        // 读取PC13按钮（下拉配置，按下时为高电平） / Считывание кнопки PC13 (настройка pull-down, при нажатии высокий уровень)
        btn2 = (GPIOC->IDR >> BUTTON2_PIN) & 1;
        // 更新全局变量 / Обновление глобальной переменной
        pc13_switch_state = btn2;

        // ==========================
        // 处理按钮 2 (PC13)：每按 5 次切换模式 / Обработка кнопки 2 (PC13): переключение режима каждые 5 нажатий
        // ==========================
        if(btn2 == 1 && button2_last == 0)   // rising edge (下拉配置，按下为高) / фронт нарастания (настройка pull-down, при нажатии высокий)
        {
            button2_count++;
            pc13_press_total++; // 增加总按压次数 / Увеличение общего количества нажатий
            if(button2_count >= 5)
            {
                mode ^= 1;           // 切换模式 / Переключение режима
                button2_count = 0;   // 清零计数 / Обнуление счетчика
                led_step = 0;        // 重置LED步骤 / Сброс счетчика светодиодов
                switch_operation_count++; // 增加模式切换次数 / Увеличение количества переключений режимов
                if(mode == 1)
                {
                    // 进入模式1：点亮LED4，关闭其他LED / Вход в режим 1: включение светодиода LED4, выключение других светодиодов
                    set_PC8_as_output();
                    GPIOC->BSRR = (1 << BUTTON1_PIN);  // 点亮LED4 / Включение светодиода LED4
                    // 关闭PB0, PB7, PB14 / Выключение PB0, PB7, PB14
                    GPIOB->BSRR = 
                        (1 << (LED1_PIN + 16)) |
                        (1 << (LED2_PIN + 16)) |
                        (1 << (LED3_PIN + 16));
                    lighting_sequence = 0; // 所有LED熄灭 / Все светодиоды выключены
                }
                else
                {
                    // 进入模式0：熄灭LED4，PC8切换回输入模式 / Вход в режим 0: выключение светодиода LED4, PC8 переключается обратно во вход
                    set_PC8_as_input();
                    // 确保LED4熄灭（如果之前是输出模式） / Гарантированное выключение светодиода LED4 (если ранее был в режиме вывода)
                    GPIOC->BSRR = (1 << (BUTTON1_PIN + 16));
                    // 所有LED初始状态为熄灭 / Все светодиоды изначально выключены
                    GPIOB->BSRR = 
                        (1 << (LED1_PIN + 16)) |
                        (1 << (LED2_PIN + 16)) |
                        (1 << (LED3_PIN + 16));
                    lighting_sequence = 0; // 所有LED熄灭 / Все светодиоды выключены
                }
                // 更新全局变量 / Обновление глобальной переменной
                operational_mode = mode;
            }
        }
        button2_last = btn2;

        // ==========================
        // 模式 1：按钮 1 禁用 + LED4亮起 / Режим 1: отключение кнопки 1 + включение светодиода LED4
        // ==========================
        if(mode == 1)
        {
            // LED4保持亮起，按钮1功能被禁用 / Светодиод LED4 остается включенным, функция кнопки 1 отключена
            delay(300000);
            continue;
        }

        // ==========================
        // 模式 0：按钮 1 依次点亮 LED1-3，然后全灭，循环 / Режим 0: кнопка 1 последовательно включает светодиоды LED1-3, затем все выключаются, цикл
        // ==========================
        if(btn1 == 0 && button1_last == 1)   // falling edge (上拉配置，按下为低) / фронт спада (настройка pull-up, при нажатии низкий)
        {
            // 每次按下时递增led_step，范围为1-4 / При каждом нажатии увеличивается led_step, диапазон 1-4
            led_step = (led_step % 4) + 1; // 1,2,3,4,1,2,3,4...
            // 更新全局变量 / Обновление глобальной переменной
            lighting_sequence = led_step;
            
            // 如果是第4步，关闭所有LED / Если это 4-й шаг, выключить все светодиоды
            if(led_step == 4) {
                // 关闭所有LED / Выключить все светодиоды
                GPIOB->BSRR = 
                    (1 << (LED1_PIN + 16)) |
                    (1 << (LED2_PIN + 16)) |
                    (1 << (LED3_PIN + 16));
            } 
            else 
            {
                // 点亮对应的LED，不关闭之前的LED / Включить соответствующий светодиод, не выключая предыдущие
                if(led_step == 1) {
                    GPIOB->BSRR = (1 << LED1_PIN);  // 点亮LED1 (PB0) / Включить LED1 (PB0)
                }
                else if(led_step == 2) {
                    GPIOB->BSRR = (1 << LED2_PIN);  // 点亮LED2 (PB7) / Включить LED2 (PB7)
                }
                else if(led_step == 3) {
                    GPIOB->BSRR = (1 << LED3_PIN);  // 点亮LED3 (PB14) / Включить LED3 (PB14)
                }
            }
        }
        button1_last = btn1;
        delay(300000);
    }
}