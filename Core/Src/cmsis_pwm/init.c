#include "init.h"

void GPIO_Ini(void)
{
    SET_BIT(RCC->AHB1ENR, RCC_AHB1ENR_GPIODEN | RCC_AHB1ENR_GPIOEEN);
    (void)READ_REG(RCC->AHB1ENR); //типо задержка на включение тактирования

    // PD13–PD15 — штатные светодиоды.
    GPIOD->BSRR = GPIO_BSRR_BR_13 | GPIO_BSRR_BR_14 | GPIO_BSRR_BR_15;
    MODIFY_REG(GPIOD->MODER, GPIO_MODER_MODER13 | GPIO_MODER_MODER14 | GPIO_MODER_MODER15,
                            GPIO_MODER_MODER13_0 | GPIO_MODER_MODER14_0 | GPIO_MODER_MODER15_0);

    // PE7–PE9 — кнопки с подтяжкой.
    CLEAR_BIT(GPIOE->MODER, GPIO_MODER_MODER7 | GPIO_MODER_MODER8 |
                           GPIO_MODER_MODER9 | GPIO_MODER_MODER10);
    MODIFY_REG(GPIOE->PUPDR, GPIO_PUPDR_PUPDR7 | GPIO_PUPDR_PUPDR8 |
                            GPIO_PUPDR_PUPDR9 | GPIO_PUPDR_PUPDR10,
                            GPIO_PUPDR_PUPDR7_0 | GPIO_PUPDR_PUPDR8_0 | GPIO_PUPDR_PUPDR9_0);
    SET_BIT(GPIOE->OTYPER, GPIO_OTYPER_OT_9);
    GPIOE->BSRR = GPIO_BSRR_BR_9;
    MODIFY_REG(GPIOE->AFR[1], GPIO_AFRH_AFSEL10, GPIO_AFRH_AFSEL10_0);

    SET_BIT(RCC->APB1ENR, RCC_APB1ENR_TIM2EN);
    (void)READ_REG(RCC->APB1ENR);
    // HSI 16 МГц, один отсчёт TIM2 равен 1 мс.
    TIM2->PSC = 16000U - 1U;
    TIM2->ARR = UINT32_MAX;
    TIM2->EGR = TIM_EGR_UG;
    TIM2->CR1 = TIM_CR1_CEN;

    SET_BIT(RCC->APB2ENR, RCC_APB2ENR_TIM1EN);
    (void)READ_REG(RCC->APB2ENR);

    TIM1->PSC = 16000U - 1U; // Делитель частоты таймера
    TIM1->ARR = 1000U - 1U; //послднее значение счетчика
    TIM1->CCR2 = 500U;//порог сравнения для
    TIM1->CCMR1 = TIM_CCMR1_OC2M_1 | TIM_CCMR1_OC2M_2 | TIM_CCMR1_OC2PE;
    TIM1->CCER = TIM_CCER_CC2NE | TIM_CCER_CC2NP;
    TIM1->BDTR = TIM_BDTR_MOE;
    TIM1->EGR = TIM_EGR_UG;
    TIM1->CR1 = TIM_CR1_ARPE | TIM_CR1_CEN;
}
