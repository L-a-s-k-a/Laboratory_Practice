#include "init.h"
void GPIO_Init(void){
    RCC_GPIO_EN |= RCC_GPIOB_EN + RCC_GPIOC_EN;
    GPIOB_MODER |= LED_1_MODE_OUT;
    GPIOB_MODER |= LED_2_MODE_OUT;
    GPIOB_MODER |= LED_3_MODE_OUT;
    GPIOB_OTYPER &= ~LED_1_OTYPE_PP;
    GPIOB_OTYPER &= ~LED_2_OTYPE_PP;
    GPIOB_OTYPER &= ~LED_3_OTYPE_PP;
    GPIOB_OSPEEDR |= LED_1_SPEED_MID;
    GPIOB_OSPEEDR |= LED_2_SPEED_MID;
    GPIOB_OSPEEDR |= LED_3_SPEED_MID;
    GPIOB_PUPDR &= ~LED_1_PUPDR_NO;
    GPIOB_PUPDR &= ~LED_2_PUPDR_NO;
    GPIOB_PUPDR &= ~LED_3_PUPDR_NO;
    GPIOC_MODER &= ~BUT_1_MODE_IN;
    GPIOC_MODER &= ~BUT_2_MODE_IN;
    GPIOC_PUPDR |= BUT_1_PUPDR_PUP;
    GPIOC_PUPDR |= BUT_2_PUPDR_PUP;
    SET_BIT(RCC->AHB1ENR, RCC_AHB1ENR_GPIOBEN | RCC_AHB1ENR_GPIOCEN);
    SET_BIT(GPIOB->MODER, GPIO_MODER_MODE5_0);
    SET_BIT(GPIOB->MODER, GPIO_MODER_MODE8_0);
    SET_BIT(GPIOB->MODER, GPIO_MODER_MODE12_0);
    CLEAR_BIT(GPIOB->OTYPER, GPIO_OTYPER_OT_5);
    CLEAR_BIT(GPIOB->OTYPER, GPIO_OTYPER_OT8);
    CLEAR_BIT(GPIOB->OTYPER, GPIO_OTYPER_OT12);
    SET_BIT(GPIOB->OSPEEDR, GPIO_OSPEEDER_OSPEEDR5_0);
    SET_BIT(GPIOB->OSPEEDR, GPIO_OSPEEDER_OSPEEDR8_0);
    SET_BIT(GPIOB->OSPEEDR, GPIO_OSPEEDER_OSPEEDR12_0);
    CLEAR_BIT(GPIOB->PUPDR, GPIO_PUPDR_PUPD5_0);
    CLEAR_BIT(GPIOB->PUPDR, GPIO_PUPDR_PUPD8_0);
    CLEAR_BIT(GPIOB->PUPDR, GPIO_PUPDR_PUPD12_0);
    CLEAR_BIT(GPIOC->MODER, GPIO_MODER_MODE6);
    CLEAR_BIT(GPIOC->MODER, GPIO_MODER_MODE7);
    CLEAR_BIT(GPIOC->PUPDR, GPIO_PUPDR_PUPD6);
    SET_BIT(GPIOC->PUPDR, GPIO_PUPDR_PUPD6_0);
    CLEAR_BIT(GPIOC->PUPDR, GPIO_PUPDR_PUPD7);
    SET_BIT(GPIOC->PUPDR, GPIO_PUPDR_PUPD7_0);
}

    