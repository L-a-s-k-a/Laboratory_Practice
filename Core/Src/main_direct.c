#include <stdint.h>

volatile uint8_t flag = 0;
// volatile запрещает компилятору оптимизировать переменную

volatile uint8_t leds_on = 0;

volatile uint8_t press_cnt = 0;

void delay(volatile uint32_t t) // Функция программной задержки
{
    while (t--) {}
}

void leds_set(uint8_t n) // Функция управления, принимает количество вкл LED
{
    // LED1 PB0, GPIOB BSRR
    if (n >= 1) { *(volatile uint32_t*)(0x40020400UL + 0x18UL) = 0x00000001UL; }
    // Если нужно включить 1+ светодиодов, записываем 1 в бит 0 регистра BSRR порта B (установка PB0)
    // Адрес 0x40020400 - база GPIOB, смещение 0x18 - регистр BSRR
    // Значение 0x00000001 - бит 0 установлен
    else { *(volatile uint32_t*)(0x40020400UL + 0x18UL) = 0x00010000UL; }
    // Иначе записываем 1 в бит 16 регистра BSRR (сброс PB0)
    // Значение 0x00010000 - бит 16 установлен

    // LED2 PB7, GPIOB BSRR
    if (n >= 2) { *(volatile uint32_t*)(0x40020400UL + 0x18UL) = 0x00000080UL; }
    // Если нужно включить 2+ светодиодов, устанавливаем бит 7 (PB7)
    // 0x00000080 = 0b10000000 = бит 7
    else { *(volatile uint32_t*)(0x40020400UL + 0x18UL) = 0x00800000UL; }
    // Иначе сбрасываем бит 7 через бит 23 (7+16)
    // 0x00800000 = бит 23

    // LED3 PB14, GPIOB BSRR
    if (n >= 3) { *(volatile uint32_t*)(0x40020400UL + 0x18UL) = 0x00004000UL; }
    // Если нужно включить 3+ светодиодов, устанавливаем бит 14 (PB14)
    // 0x00004000 = бит 14
    else { *(volatile uint32_t*)(0x40020400UL + 0x18UL) = 0x40000000UL; }
    // Иначе сбрасываем бит 14 через бит 30 (14+16)
    // 0x40000000 = бит 30

    // LED4 PA6, GPIOA BSRR
    if (n >= 4) { *(volatile uint32_t*)(0x40020000UL + 0x18UL) = 0x00000040UL; }
    // Если нужно включить 4 светодиода, устанавливаем бит 6 порта A (PA6)
    // Адрес 0x40020000 - база GPIOA, смещение 0x18 - BSRR
    // 0x00000040 = бит 6
    else { *(volatile uint32_t*)(0x40020000UL + 0x18UL) = 0x00400000UL; }
    // Иначе сбрасываем бит 6 через бит 22 (6+16)
    // 0x00400000 = бит 22
}

uint8_t btn_pressed(void)
{
    return (*(volatile uint32_t*)(0x40020800UL + 0x10UL) & 0x2000UL) ? 1 : 0;
    // Читаем регистр IDR порта C (адрес 0x40020800 + смещение 0x10 = 0x40020810)
    // Делаем побитовое И с маской 0x2000 (бит 13)
    // 0x2000 = 0b0010 0000 0000 0000 = бит 13 установлен
    // Если результат не равен 0 (бит 13 = 1), возвращаем 1, иначе 0
}

int main(void)
{
    *(volatile uint32_t*)(0x40023800UL + 0x30UL) |= 0x07UL;
    // Включаем тактирование портов GPIOA, GPIOB, GPIOC
    // Адрес 0x40023800 - база RCC, смещение 0x30 - регистр AHB1ENR
    // Значение 0x07 = 0b00000111 = биты 0, 1, 2 (GPIOAEN, GPIOBEN, GPIOCEN)
    // Операция |= сохраняет остальные биты регистра

    *(volatile uint32_t*)(0x40020400UL + 0x00UL) |= 0x10004001UL;
    // Настраиваем пины PB0, PB7, PB14 на режим выхода
    // Адрес 0x40020400 - база GPIOB, смещение 0x00 - регистр MODER
    // Значение 0x10004001: биты 0-1 (PB0): 01 = Output, биты 14-15 (PB7): 01 = Output, биты 28-29 (PB14): 01 = Output

    *(volatile uint32_t*)(0x40020000UL + 0x00UL) |= 0x00001000UL;
    // Настраиваем пин PA6 на режим выхода
    // Адрес 0x40020000 - база GPIOA, смещение 0x00 - MODER
    // Значение 0x00001000: биты 12-13 (PA6): 01 = Output

    // Пин PC13 (кнопка) остается в режиме входа по умолчанию
    // После сброса MODER = 0 (вход), OTYPER = 0 (push-pull), PUPDR = 0 (без подтяжки)

    leds_set(0);
    // Вызываем функцию управления светодиодами с аргументом 0 (все выкл)

    while (1)
    {
        if (btn_pressed())
            // Проверяем, нажата ли кнопка
        {
            flag = 1;

            delay(100000UL);

            if (btn_pressed())
            {
                press_cnt++;
                // Увеличиваем счетчик нажатий на 1

                if (press_cnt >= 6)
                    // Если счетчик достиг 6
                {
                    press_cnt = 0;
                    leds_on = 4;
                    // Устанавливаем количество включенных светодиодов в 4 (все включены)
                }
                else if (press_cnt > 4)
                    // Если счетчик равен 5
                {
                    leds_on = 0;
                }
                else
                    // Если счетчик от 1 до 4
                {
                    leds_on = press_cnt;
                    // Количество включенных светодиодов равно номеру нажатия
                }

                leds_set(leds_on);
                // Применяем новое состояние к физическим пинам светодиодов

                while (btn_pressed()) {}

                delay(100000UL);
            }
            flag = 0;
        }
        else
            // Если кнопка не нажата
        {
            flag = 0;
        }
    }
}